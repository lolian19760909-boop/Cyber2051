import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=name=>fs.readFileSync(new URL(name,import.meta.url),'utf8');
const data=JSON.parse(read('../../卡片源码/地图/central-data.js').slice('window.TOKYO_ATLAS='.length).replace(/;\s*$/,''));
const places=[...data.nodes,...data.services,...data.districtExpansion.places,...data.terrainContext.places];
const source=read('../../卡片源码/地图/atlas.js'),predicate=source.match(/^  function matchesPlace\(.*$/m)?.[0];
const placeRegion=source.match(/^  const placeRegion=.*$/m)?.[0];assert.ok(placeRegion);
assert.ok(predicate,'Use the actual renderer predicate.');
const context=vm.createContext({state:{type:'all',filterRegion:null},query:'',sector:false,regionsById:new Map(data.regions.map(r=>[r.id,r])),placeType:n=>n.type||(n.id==='a-yang-clinic'?'implant':'legacy')});
vm.runInContext(placeRegion+'\n'+predicate,context);
const checks=[],check=(name,fn)=>{fn();checks.push(name);};
const found=type=>places.filter(n=>context.matchesPlace(n,type)).map(n=>n.id);
check('默认公寓筛选仍能搜索全部地区',()=>assert.equal(found('apartment').length,4));
context.state.filterRegion='underpool';
check('暗池检索包含红花街与CiRCLE',()=>{for(const id of ['beni-street','circle'])assert.ok(found('all').includes(id));});
check('暗池公寓仅显示该区住所',()=>assert.deepEqual(found('apartment'),['rana-shifune-home']));
check('暗池没有护卫线索时不混入区外结果',()=>assert.deepEqual(found('escort'),[]));
context.query='赤羽';
check('关键词不能绕过明确的地区筛选',()=>assert.deepEqual(found('all'),[]));
context.state.filterRegion='lowtown';
check('荒川下城仍能找到三个赤羽关联节点',()=>assert.equal(found('all').length,3));
context.query='';
check('分类计数与同地区的真实结果一致',()=>{for(const type of ['all','legacy',...data.serviceTypes.map(t=>t.id)])assert.ok(found(type).every(id=>places.find(n=>n.id===id).group==='lowtown'));});
context.state.filterRegion=null;context.query='赤羽';
check('清空地区限制后恢复全图关键词检索',()=>assert.equal(found('all').length,3));
console.log(JSON.stringify({checks:checks.length,checked:checks},null,2));
