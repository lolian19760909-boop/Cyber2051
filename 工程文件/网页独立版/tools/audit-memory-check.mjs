import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
const root=fileURLToPath(new URL('../../',import.meta.url)).replace(/\\/g,'/');
const web=root+'网页独立版/';
const mod=rel=>import(pathToFileURL(web+'src/'+rel).href);
const require=createRequire(import.meta.url),parser=require(root+'卡片源码/Gal/parser.js'),knowledge=require(root+'卡片源码/长期记忆/knowledge.js');
const {loadContract}=await mod('memory/contract.mjs'),contract=await loadContract();
const {createMemoryStatePort}=await mod('store/memory.mjs'),{createMemoryService}=await mod('memory/service.mjs'),{buildMemorySources,narrativeSegments}=await mod('memory/source.mjs'),{prepareArchive}=await mod('memory/archive.mjs');
const {createContextService}=await mod('context/service.mjs');
const identity={accountId:'audit-only',runId:'synthetic-memory',branchId:'main',mode:'local'};
const state={terminal:{ensemble:{actors:{player:{actorId:'player',name:'玩家'},wb_4:{actorId:'wb_4',name:'高松灯'}},control:{actorId:'wb_4',viewpointActorId:'wb_4',revision:1}}}};
const privateQuote='只有高松灯知道密码藏在旧车站的第三根柱子。';
const publicQuote='玩家与高松灯在诊所共同交付了红线纸袋。';
const story='<cxx-story>'+publicQuote+'<cxx-say speaker="高松灯" kind="thought">'+privateQuote+'</cxx-say></cxx-story>';
const port=createMemoryStatePort({accountId:identity.accountId});
await port.commit({...identity,nodeId:'one',operationId:'op-one',parentNodeId:null,expectedRevision:0,stateAfter:state,beforeState:{},message:{role:'assistant',raw:story,binding:{viewpointActorId:'player'},attemptId:'attempt-one'},profile:{name:'玩家'}});
const nodes=await port.readLineage(identity.runId),sources=await buildMemorySources({nodes,identity,parser}),sourceRow=sources[0],task={taskId:'audit-archive',source:{...sourceRow.source,quote:sourceRow.plain.slice(0,160)}};
const makeRecords=(kind,actor,quote)=>({records:[{table:'事件记录',quote,cells:{事件编号:'EV_local',类别:kind,内容:'隐蔽信息',参与人物:[actor],关联纪要:''}},{table:'人物认知',quote,cells:{认知编号:'KN_local',人物编号:actor,事件编号:'EV_local',认知类型:'知道',所知内容:'UNIQUE_ORIGINAL_COGNITION',获知途径:'本人心声',告知者:'',取代认知:''}}]});
const actors=[{actorId:'player',name:'玩家'},{actorId:'wb_4',name:'高松灯'}];
const prepare=(raw,segments)=>prepareArchive({raw,task,chunkIndex:0,sourceRow,segments,actors,existing:[],contract,knowledge,sourceRows:sources,now:()=>new Date(0).toISOString()});
const records=prepare(makeRecords('心声','wb_4',privateQuote),narrativeSegments(story,parser,actors));
await port.putRecords('memories',identity.runId,records);
const service=createMemoryService({statePort:port,identity,parser,contract,knowledge,lockManager:null});
await service.restore({nodes,state});await service.configure({enabled:true});
const cognition=records.find(r=>r.table==='人物认知');
await service.setMode(cognition.id,'excluded');
const excludedProjection=service.projectHistory(story,{actorId:'wb_4',nodeId:'one'});
const recalled=await service.recall({query:'UNIQUE_ORIGINAL_COGNITION',actorId:'wb_4'});
assert.equal(recalled.selected.length,0);
assert.doesNotMatch(excludedProjection,/UNIQUE_ORIGINAL_COGNITION/);assert.match(excludedProjection,/只有高松灯知道密码/);
const context=createContextService({statePort:port,identity,parser,memory:service,projectHistory:(text,opts)=>service.projectHistory(text,opts)});
await context.restore({nodes,state,actorId:'wb_4'});
assert.equal(context.rows.length,0); // Ordinary context correctly filters the other viewpoint.
const preview=await service.previewTimeline({actorId:'wb_4'});
assert.doesNotMatch(preview.initialItems.map(r=>r.text).join('\n'),/UNIQUE_ORIGINAL_COGNITION/);
await service.setMode(cognition.id,'auto');await service.correct(cognition.id,'UNIQUE_CORRECTED_COGNITION');
const correctedProjection=service.projectHistory(story,{actorId:'wb_4',nodeId:'one'});
assert.doesNotMatch(correctedProjection,/UNIQUE_ORIGINAL_COGNITION/);assert.match(correctedProjection,/UNIQUE_CORRECTED_COGNITION/);assert.match(correctedProjection,/只有高松灯知道密码/);

const correctedPreview=await service.previewTimeline({actorId:'wb_4'});assert.match(correctedPreview.initialItems.map(r=>r.text).join('\n'),/UNIQUE_CORRECTED_COGNITION/);console.log(JSON.stringify({passed:4,total:4,scope:'Actual memory/timeline modules synthetic valid cognition, no model request'}));
